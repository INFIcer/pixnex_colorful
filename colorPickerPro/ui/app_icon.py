"""The pixnex application icon.

One multi-size ``pixnex.ico`` carries the whole visual identity:

- ``pixnex.spec`` embeds it into the packaged ``pixnex.exe`` (``EXE(icon=...)``)
  *and* bundles it as data, so a frozen build can still load it at runtime;
- :func:`app_icon` hands the same :class:`QIcon` to ``QApplication`` and to the
  custom title bar.

The file is generated by ``tools/gen_app_icon.py`` – never hand-edited.  The
path rule is the same in both layouts because PyInstaller copies the data file
to ``sys._MEIPASS`` (which is also ``__file__``'s root in a frozen build):

    <project root>/pixnex.ico
    <_MEIPASS>/pixnex.ico
"""

from __future__ import annotations

from functools import lru_cache
from pathlib import Path

from PySide6.QtGui import QIcon

#: ``colorPickerPro/ui/app_icon.py`` → project root (or PyInstaller ``_MEIPASS``)
ICON_FILE = Path(__file__).resolve().parents[2] / "pixnex.ico"


@lru_cache(maxsize=1)
def app_icon() -> QIcon:
    """Return the application icon (empty ``QIcon`` when the file is missing)."""
    return QIcon(str(ICON_FILE)) if ICON_FILE.is_file() else QIcon()


__all__ = ["ICON_FILE", "app_icon"]
